import React, { useState, useEffect } from 'react';
import { Network, Save, AlertCircle, CheckCircle2, Info } from 'lucide-react';
import api from '../../services/api';
import type { ReferralSettingDto } from '../../types';

export const AdminReferralSettings: React.FC = () => {
  const [form, setForm] = useState({ l1: '15', l2: '10', l3: '5', l4: '2', l5: '1' });
  const [isLoading, setIsLoading] = useState(true);
  const [isSaving, setIsSaving] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [success, setSuccess] = useState<string | null>(null);

  useEffect(() => {
    const fetch = async () => {
      try {
        const res = await api.get<ReferralSettingDto>('/admin/referral-settings');
        setForm({
          l1: (res.data.level1Rate * 100).toFixed(0),
          l2: (res.data.level2Rate * 100).toFixed(0),
          l3: (res.data.level3Rate * 100).toFixed(0),
          l4: (res.data.level4Rate * 100).toFixed(1),
          l5: (res.data.level5Rate * 100).toFixed(0),
        });
      } catch {
        // Use defaults
      } finally {
        setIsLoading(false);
      }
    };
    fetch();
  }, []);

  const handleSave = async (e: React.FormEvent) => {
    e.preventDefault();
    setError(null);
    setSuccess(null);
    setIsSaving(true);
    try {
      await api.put('/admin/referral-settings', {
        level1Rate: parseFloat(form.l1) / 100,
        level2Rate: parseFloat(form.l2) / 100,
        level3Rate: parseFloat(form.l3) / 100,
        level4Rate: parseFloat(form.l4) / 100,
        level5Rate: parseFloat(form.l5) / 100,
      });
      setSuccess('Referral commission rates updated. Applied to new ROI cycles going forward.');
    } catch (err: any) {
      setError(err.response?.data?.message || 'Failed to save referral settings.');
    } finally {
      setIsSaving(false);
    }
  };

  const levels = [
    { key: 'l1' as keyof typeof form, label: 'Level 1 (Direct)', example: 'Direct referral: 15% of their daily ROI' },
    { key: 'l2' as keyof typeof form, label: 'Level 2', example: 'Level 2 downline: 10% of their daily ROI' },
    { key: 'l3' as keyof typeof form, label: 'Level 3', example: 'Level 3 downline: 5% of their daily ROI' },
    { key: 'l4' as keyof typeof form, label: 'Level 4', example: 'Level 4 downline: 2% of their daily ROI' },
    { key: 'l5' as keyof typeof form, label: 'Level 5', example: 'Level 5 downline: 1% of their daily ROI' },
  ];

  return (
    <div className="space-y-6 max-w-2xl">
      <div>
        <h2 className="text-xl font-bold text-white flex items-center gap-2">
          <Network className="w-5 h-5 text-cyan-400" />
          5-Level Referral Commission Settings
        </h2>
        <p className="text-xs text-slate-400 mt-0.5">
          Commissions are calculated from downline daily ROI — not from investment principal.
        </p>
      </div>

      <div className="p-4 rounded-xl bg-cyan-950/20 border border-cyan-500/20 flex items-start gap-3 text-xs text-cyan-300">
        <Info className="w-4 h-4 shrink-0 mt-0.5" />
        <span>
          Example: If a Level 1 downline earns $8 daily ROI, and Level 1 commission is 15%, you receive $1.20.
          These rates apply to the daily ROI generated by each downline investment, up to 5 levels deep.
        </span>
      </div>

      {isLoading ? (
        <div className="flex items-center justify-center py-12">
          <div className="w-8 h-8 border-2 border-cyan-500 border-t-transparent rounded-full animate-spin" />
        </div>
      ) : (
        <form onSubmit={handleSave} className="space-y-4">
          {error && (
            <div className="p-3 rounded-xl bg-rose-500/10 border border-rose-500/30 flex items-center gap-2 text-xs text-rose-300">
              <AlertCircle className="w-4 h-4" /><span>{error}</span>
            </div>
          )}
          {success && (
            <div className="p-3 rounded-xl bg-emerald-500/10 border border-emerald-500/30 flex items-center gap-2 text-xs text-emerald-300">
              <CheckCircle2 className="w-4 h-4" /><span>{success}</span>
            </div>
          )}

          <div className="valexis-card rounded-2xl p-6 space-y-4">
            {levels.map(({ key, label, example }) => (
              <div key={key} className="flex items-center gap-4">
                <div className="flex-1">
                  <label className="block text-xs font-semibold text-slate-300 mb-1">{label}</label>
                  <p className="text-[11px] text-slate-500">{example}</p>
                </div>
                <div className="relative w-32">
                  <input
                    type="number"
                    step="0.1"
                    min="0"
                    max="50"
                    value={form[key]}
                    onChange={e => setForm(f => ({ ...f, [key]: e.target.value }))}
                    className="w-full px-3 py-2 rounded-xl bg-slate-900 border border-slate-700 text-white font-mono text-sm font-bold text-right focus:outline-none focus:border-cyan-500 pr-8"
                  />
                  <span className="absolute right-3 top-2 text-xs text-slate-400 font-semibold">%</span>
                </div>
              </div>
            ))}
          </div>

          <button
            type="submit"
            disabled={isSaving}
            className="w-full valexis-gradient-btn py-3 rounded-xl text-white font-semibold text-sm flex items-center justify-center gap-2 disabled:opacity-40 cursor-pointer"
          >
            {isSaving ? <div className="w-4 h-4 border-2 border-white border-t-transparent rounded-full animate-spin" /> : <><Save className="w-4 h-4" /><span>Save Commission Rates</span></>}
          </button>
        </form>
      )}
    </div>
  );
};
